  'country_code,gender,category,club_name,club_country_code,' +
  'ranking_value,rank,ranked_at,confidence_level,total_players';

function makeRow(line: string, gender: 'M' | 'F'): string {
  const [rank, rawLast, rawFirst, cc3, points, pid] = line.split('|');
  const last = tc(rawLast);
  const first = tc(rawFirst);
  const cc2 = CC[cc3] ?? 'XX';
  const url =
    `https://results.ittf.link/index.php/player-profile/list/60` +
    `?resetfilters=1&vw_profiles___player_id_raw=${pid}`;
  return `ITTF,${pid},${url},${first},${last},${first} ${last},${cc2},${gender},SENIOR,,,${points},${rank},2026-05-12,HIGH,`;
}

